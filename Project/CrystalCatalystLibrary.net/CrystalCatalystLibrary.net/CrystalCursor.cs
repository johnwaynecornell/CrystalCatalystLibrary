namespace CrystalCatalystLibrary.net;

/// <summary>
/// Specifies the standard mouse cursor types.
/// </summary>
public enum CrystalCursor
{
    /// <summary>Default arrow cursor.</summary>
    Arrow = 0,
    /// <summary>Text input cursor (I-beam).</summary>
    Text = 1,
    /// <summary>Wait or busy cursor.</summary>
    Wait = 2,
    /// <summary>Crosshair cursor.</summary>
    Crosshair = 3,
    /// <summary>Move cursor.</summary>
    Move = 4,
    /// <summary>Northwest-southeast resize cursor.</summary>
    NWSEResize = 5,
    /// <summary>Northeast-southwest resize cursor.</summary>
    NESWResize = 6,
    /// <summary>West-east (horizontal) resize cursor.</summary>
    WEResize = 7,
    /// <summary>North-south (vertical) resize cursor.</summary>
    NSResize = 8,
    /// <summary>Hand cursor, typically for links.</summary>
    Hand = 9,
    /// <summary>Indicates an action is not allowed.</summary>
    NotAllowed = 10
}